"""Regenerate the local and Supabase catalogs from one checked-in CSV.

To refresh USDA values, pass the pinned SR Legacy 2018 CSV ZIP as --usda-zip.
The mapped FDC IDs and Russian names live in catalog/produce_map.csv.
"""

import argparse
import csv
import io
import zipfile
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / 'catalog' / 'products.csv'
MAP = ROOT / 'catalog' / 'produce_map.csv'
DART = ROOT / 'lib' / 'models' / 'seed_products.dart'
SQL = ROOT / 'supabase' / 'schema.sql'
FIELDS = ['id', 'name', 'name_en', 'category', 'calories', 'protein', 'fat', 'carbs', 'fdc_id', 'slv_id', 'source_description']
NUTRIENTS = {'1008': 'calories', '1003': 'protein', '1004': 'fat', '1005': 'carbs'}
def zip_rows(archive, name):
    path = next(path for path in archive.namelist() if path.endswith('/' + name + '.csv'))
    return csv.DictReader(io.TextIOWrapper(archive.open(path), encoding='utf-8-sig'))


def refresh_from_usda(archive_path):
    with CATALOG.open(newline='', encoding='utf-8') as file:
        current = {row['id']: row for row in csv.DictReader(file)}
    with MAP.open(newline='', encoding='utf-8') as file:
        mapping = list(csv.DictReader(file))
    ids = {row['fdc_id'] for row in mapping}
    with zipfile.ZipFile(archive_path) as archive:
        foods = {row['fdc_id']: row for row in zip_rows(archive, 'food') if row['fdc_id'] in ids}
        nutrients = {fdc_id: {} for fdc_id in ids}
        for row in zip_rows(archive, 'food_nutrient'):
            if row['fdc_id'] in ids and row['nutrient_id'] in NUTRIENTS:
                nutrients[row['fdc_id']][NUTRIENTS[row['nutrient_id']]] = row['amount']

    products = []
    for row in mapping:
        if current[row['id']]['slv_id']:
            continue
        fdc_id = row['fdc_id']
        food = foods[fdc_id]
        description = food['description']
        assert food['food_category_id'] in {'9', '11'} and 'raw' in description.lower(), description
        assert len(nutrients[fdc_id]) == 4, f'Missing nutrients for {fdc_id}'
        products.append({**current[row['id']], **row, **nutrients[fdc_id],
                         'slv_id': '', 'source_description': description})
    products += [row for row in current.values() if not row['fdc_id']]

    with CATALOG.open('w', newline='', encoding='utf-8') as file:
        writer = csv.DictWriter(file, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(products)


def dart_string(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def sql_string(value):
    return "'" + value.replace("'", "''") + "'"


def generate():
    with CATALOG.open(newline='', encoding='utf-8') as file:
        rows = list(csv.DictReader(file))
    assert len({row['id'] for row in rows}) == len(rows)
    assert len({row['name'] for row in rows}) == len(rows)
    assert len({row['fdc_id'] for row in rows if row['fdc_id']}) == len([row for row in rows if row['fdc_id']])
    assert len({row['slv_id'] for row in rows if row['slv_id']}) == len([row for row in rows if row['slv_id']])

    dart_lines = ["part of 'product.dart';", '', '// Generated by scripts/generate_catalog.py from catalog/products.csv.', 'const seedProducts = <Product>[']
    sql_lines = ['-- BEGIN GENERATED SEEDS', '-- Generated by scripts/generate_catalog.py from catalog/products.csv.', 'insert into public.products (name, name_en, calories, protein, fat, carbs, slv_id, fdc_id) values']
    for index, row in enumerate(rows):
        dart_lines.append(
            '  Product(id: {id}, name: {name}, nameEn: {name_en}, calories: {calories}, protein: {protein}, fat: {fat}, carbs: {carbs}{slv_dart}{fdc_dart}),'.format(
                **{**row, 'id': dart_string(row['id']), 'name': dart_string(row['name']),
                   'name_en': dart_string(row['name_en']),
                   'slv_dart': ', slvId: ' + row['slv_id'] if row['slv_id'] else '',
                   'fdc_dart': ', fdcId: ' + row['fdc_id'] if row['fdc_id'] else ''}))
        sql_lines.append(
            '  ({name}, {name_en}, {calories}, {protein}, {fat}, {carbs}, {slv_sql}, {fdc_sql}){end}'.format(
                **{**row, 'name': sql_string(row['name']), 'name_en': sql_string(row['name_en']),
                   'slv_sql': row['slv_id'] or 'null', 'fdc_sql': row['fdc_id'] or 'null',
                   'end': ',' if index < len(rows) - 1 else ''}))
    dart_lines += ['];', '']
    sql_lines += [
        'on conflict (name) where owner_id is null do update set',
        '  name_en = excluded.name_en, calories = excluded.calories, protein = excluded.protein,',
        '  fat = excluded.fat, carbs = excluded.carbs, slv_id = excluded.slv_id, fdc_id = excluded.fdc_id;',
        '-- END GENERATED SEEDS',
    ]
    DART.write_text('\n'.join(dart_lines), encoding='utf-8')
    sql = SQL.read_text(encoding='utf-8')
    start = sql.index('-- BEGIN GENERATED SEEDS')
    end = sql.index('-- END GENERATED SEEDS') + len('-- END GENERATED SEEDS')
    SQL.write_text(sql[:start] + '\n'.join(sql_lines) + sql[end:], encoding='utf-8')
    print(f'Generated {len(rows)} products.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--usda-zip', type=Path, help='USDA FoodData Central SR Legacy 2018 CSV ZIP')
    args = parser.parse_args()
    if args.usda_zip:
        refresh_from_usda(args.usda_zip)
    generate()
